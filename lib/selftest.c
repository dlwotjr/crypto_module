int selftest_run_startup(KCMVP_SELFTEST_STATUS *status)
{
    if (status == NULL)
        return KCMVP_ERROR_INVALID_PARAM;

    memset(status, 0, sizeof(*status));

    if (aria_kat() != KCMVP_SUCCESS)
        return KCMVP_ERROR_SELF_TEST;
    status->aria_passed = 1;

    if (sha3_kat() != KCMVP_SUCCESS)
        return KCMVP_ERROR_SELF_TEST;
    status->sha3_passed = 1;

    if (hmac_sha3_kat() != KCMVP_SUCCESS)
        return KCMVP_ERROR_SELF_TEST;
    status->hmac_sha3_passed = 1;

    if (hash_drbg_kat() != KCMVP_SUCCESS)
        return KCMVP_ERROR_SELF_TEST;
    status->hash_drbg_passed = 1;

    if (ecc_p256_kat() != KCMVP_SUCCESS)
        return KCMVP_ERROR_SELF_TEST;
    status->ecc_p256_passed = 1;

    if (mlkem768_kat() != KCMVP_SUCCESS ||
        should_force_failure(KCMVP_SELFTEST_FORCE_MLKEM768))
        return KCMVP_ERROR_SELF_TEST;
    status->mlkem768_passed = 1;

    return KCMVP_SUCCESS;
}
